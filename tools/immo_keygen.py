#!/usr/bin/env python3
"""Ayach Immo - licence key issuer (PRIVATE, for the developer only).

A key is a signed token (Ed25519). The app only contains the PUBLIC key, so
nobody can forge keys even if they fully read the app. The key carries:
    target platform | duration | random id | fingerprint(user name + phone)

  python3 immo_keygen.py init              create your signing key + lib/license_pubkey.dart (once!)
  python3 immo_keygen.py                   interactive menu (window if tkinter exists, else terminal)
  python3 immo_keygen.py gen --name "Ahmed" --phone +212600000000 --platform android --duration week
  python3 immo_keygen.py inspect <KEY>     decode and verify a key

Needs:  pip install cryptography
KEEP issuer_private.pem AND ITS PASSPHRASE SECRET AND BACKED UP. If you lose it you can
never issue keys that the published app accepts; if it leaks, anybody can.
"""
import argparse, base64, csv, datetime, getpass, hashlib, os, re, secrets, sys

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey

HERE = os.path.dirname(os.path.abspath(__file__))
PRIV = os.path.join(HERE, "issuer_private.pem")
LOG = os.path.join(HERE, "issued_keys.csv")
DART = os.path.join(HERE, "..", "lib", "license_pubkey.dart")

PLATFORMS = {"any": 0, "android": 1, "ios": 2, "windows": 3, "macos": 4, "linux": 5}
# days; 0 = forever
DURATIONS = {"day": 1, "3days": 3, "week": 7, "month": 30, "forever": 0}
DURATION_AR = {"day": "يوم", "3days": "3 أيام", "week": "أسبوع", "month": "شهر", "forever": "إلى الأبد"}
VERSION = 1
MAGIC = b"IMMO1"


def norm_name(n: str) -> str:
    return re.sub(r"\s+", " ", n.strip().lower())


def norm_phone(p: str) -> str:
    return re.sub(r"\D", "", p)[-9:]  # last 9 digits: +212 6.. and 06.. give the same value


def fingerprint(name: str, phone: str) -> bytes:
    return hashlib.sha256(b"immo-bind-v1|" + norm_name(name).encode() + b"|" + norm_phone(phone).encode()).digest()[:8]


def b32(data: bytes) -> str:
    return base64.b32encode(data).decode().rstrip("=")


def group(s: str, n: int = 6) -> str:
    return "-".join(s[i:i + n] for i in range(0, len(s), n))


def load_private() -> Ed25519PrivateKey:
    if not os.path.exists(PRIV):
        sys.exit("No signing key yet. Run:  python3 immo_keygen.py init")
    data = open(PRIV, "rb").read()
    pw = None
    if b"ENCRYPTED" in data:
        pw = os.environ.get("IMMO_KEY_PASS") or getpass.getpass("Signing-key passphrase: ")
        pw = pw.encode()
    return serialization.load_pem_private_key(data, password=pw)


def init():
    if os.path.exists(PRIV):
        sys.exit("issuer_private.pem already exists. Refusing to overwrite (that would invalidate all issued keys).")
    pw = getpass.getpass("Choose a passphrase for the signing key (empty = none, NOT recommended): ")
    key = Ed25519PrivateKey.generate()
    enc = serialization.BestAvailableEncryption(pw.encode()) if pw else serialization.NoEncryption()
    pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, enc)
    with open(PRIV, "wb") as f:
        f.write(pem)
    try:
        os.chmod(PRIV, 0o600)
    except OSError:
        pass
    pub = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    write_dart(pub)
    print("Created", PRIV)
    print("Wrote  ", os.path.abspath(DART), "  <- rebuild the app with it")
    print("BACK UP issuer_private.pem NOW and never publish it.")


def write_dart(pub: bytes):
    body = ", ".join(str(b) for b in pub)
    with open(DART, "w") as f:
        f.write("// Generated by tools/immo_keygen.py init. This is the PUBLIC key (safe to publish).\n")
        f.write(f"const List<int> kLicensePublicKey = [{body}];\n")


def make_key(name: str, phone: str, platform: str, duration: str) -> str:
    if platform not in PLATFORMS or duration not in DURATIONS:
        raise ValueError("bad platform/duration")
    if not norm_name(name) or len(norm_phone(phone)) < 6:
        raise ValueError("name and a valid phone number are required")
    payload = bytes([VERSION, PLATFORMS[platform], DURATIONS[duration]]) + secrets.token_bytes(8) + fingerprint(name, phone)
    sig = load_private().sign(MAGIC + payload)
    key = group(b32(payload + sig))
    new = not os.path.exists(LOG)
    with open(LOG, "a", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        if new:
            w.writerow(["date", "name", "phone", "platform", "duration", "key"])
        w.writerow([datetime.datetime.now().isoformat(timespec="seconds"), name, phone, platform, duration, key])
    return key


def inspect(key: str):
    s = re.sub(r"[^A-Z2-7]", "", key.upper())
    s += "=" * (-len(s) % 8)
    raw = base64.b32decode(s)
    payload, sig = raw[:19], raw[19:83]
    pub = load_private().public_key()
    try:
        pub.verify(sig, MAGIC + payload)
        ok = True
    except Exception:
        ok = False
    plat = {v: k for k, v in PLATFORMS.items()}.get(payload[1], "?")
    days = payload[2]
    print("signature valid:", ok, "| platform:", plat, "| days:", "forever" if days == 0 else days, "| nonce:", payload[3:11].hex(), "| bind:", payload[11:19].hex())


def gui():
    import tkinter as tk
    from tkinter import messagebox, ttk
    root = tk.Tk()
    root.title("Immo Key Issuer")
    pad = {"padx": 8, "pady": 4}
    name, phone = tk.StringVar(), tk.StringVar()
    plat, dur = tk.StringVar(value="android"), tk.StringVar(value="week")
    for i, (lbl, var) in enumerate([("Username", name), ("Phone", phone)]):
        ttk.Label(root, text=lbl).grid(row=i, column=0, sticky="w", **pad)
        ttk.Entry(root, textvariable=var, width=40).grid(row=i, column=1, **pad)
    ttk.Label(root, text="Platform").grid(row=2, column=0, sticky="w", **pad)
    ttk.Combobox(root, textvariable=plat, values=list(PLATFORMS), state="readonly").grid(row=2, column=1, sticky="w", **pad)
    ttk.Label(root, text="Duration").grid(row=3, column=0, sticky="w", **pad)
    ttk.Combobox(root, textvariable=dur, values=list(DURATIONS), state="readonly").grid(row=3, column=1, sticky="w", **pad)
    out = tk.Text(root, height=7, width=60, wrap="char")
    out.grid(row=5, column=0, columnspan=2, **pad)

    def run():
        try:
            k = make_key(name.get(), phone.get(), plat.get(), dur.get())
        except Exception as e:
            messagebox.showerror("Error", str(e))
            return
        out.delete("1.0", "end")
        out.insert("end", k)
        root.clipboard_clear()
        root.clipboard_append(k)

    ttk.Button(root, text="Generate (copies to clipboard)", command=run).grid(row=4, column=0, columnspan=2, **pad)
    root.mainloop()


def menu():
    print("Immo Key Issuer (terminal)")
    name = input("Username: ")
    phone = input("Phone: ")
    plat = input(f"Platform {list(PLATFORMS)}: ").strip().lower()
    dur = input(f"Duration {list(DURATIONS)}: ").strip().lower()
    print("\nKEY:\n" + make_key(name, phone, plat, dur))


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd")
    sub.add_parser("init")
    g = sub.add_parser("gen")
    g.add_argument("--name", required=True)
    g.add_argument("--phone", required=True)
    g.add_argument("--platform", choices=list(PLATFORMS), required=True)
    g.add_argument("--duration", choices=list(DURATIONS), required=True)
    i = sub.add_parser("inspect")
    i.add_argument("key")
    a = ap.parse_args()
    if a.cmd == "init":
        init()
    elif a.cmd == "gen":
        print(make_key(a.name, a.phone, a.platform, a.duration))
    elif a.cmd == "inspect":
        inspect(a.key)
    else:
        try:
            gui()
        except ImportError:
            menu()


if __name__ == "__main__":
    main()
