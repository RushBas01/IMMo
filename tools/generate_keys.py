#!/usr/bin/env python3
"""Generates activation keys (40 chars, a-z A-Z 0-9) and updates lib/key_hashes.dart.

  python3 tools/generate_keys.py            -> 100 trial + 100 permanent
  python3 tools/generate_keys.py 50 200     -> 50 trial + 200 permanent (ADDED to the existing hashes)

Plain keys go to keys/trial_keys.txt and keys/permanent_keys.txt (new batch only).
KEEP THE keys/ FOLDER PRIVATE - never put it in the app or on GitHub.
Only SHA-256 hashes are embedded in the app (lib/key_hashes.dart).
"""
import hashlib, os, re, secrets, string, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DART = os.path.join(ROOT, 'lib', 'key_hashes.dart')
ALPHABET = string.ascii_letters + string.digits

def new_key():
    return ''.join(secrets.choice(ALPHABET) for _ in range(40))

def existing(name):
    if not os.path.exists(DART):
        return set()
    m = re.search(r'const Set<String> %s = \{(.*?)\};' % name, open(DART, encoding='utf-8').read(), re.S)
    return set(re.findall(r"'([0-9a-f]{64})'", m.group(1))) if m else set()

def main():
    n_trial = int(sys.argv[1]) if len(sys.argv) > 1 else 100
    n_perm = int(sys.argv[2]) if len(sys.argv) > 2 else 100
    trial_h, perm_h = existing('trialKeyHashes'), existing('permanentKeyHashes')
    trial_keys = [new_key() for _ in range(n_trial)]
    perm_keys = [new_key() for _ in range(n_perm)]
    trial_h |= {hashlib.sha256(k.encode()).hexdigest() for k in trial_keys}
    perm_h |= {hashlib.sha256(k.encode()).hexdigest() for k in perm_keys}

    def block(name, hs):
        return 'const Set<String> %s = {\n%s\n};\n' % (name, '\n'.join("  '%s'," % h for h in sorted(hs)))

    with open(DART, 'w', encoding='utf-8') as f:
        f.write('// GENERATED by tools/generate_keys.py - only SHA-256 hashes, never the keys themselves.\n\n')
        f.write(block('trialKeyHashes', trial_h) + '\n' + block('permanentKeyHashes', perm_h))

    os.makedirs(os.path.join(ROOT, 'keys'), exist_ok=True)
    open(os.path.join(ROOT, 'keys', 'trial_keys.txt'), 'w').write('\n'.join(trial_keys) + '\n')
    open(os.path.join(ROOT, 'keys', 'permanent_keys.txt'), 'w').write('\n'.join(perm_keys) + '\n')
    print('trial: %d new (%d total) | permanent: %d new (%d total)' % (n_trial, len(trial_h), n_perm, len(perm_h)))

main()
